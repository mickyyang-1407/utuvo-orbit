import AppKit
import Combine
import ImageIO
import OrbitCore

struct ClipboardEntry: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String?
    var png: Data?
    var date = Date()
    var pinned = false
    var byteCount: Int { (text?.utf8.count ?? 0) + (png?.count ?? 0) }
    var valid: Bool {
        guard (text != nil) != (png != nil), byteCount > 0, byteCount <= 4_000_000 else { return false }
        if let text { return text.utf8.count <= 200_000 }
        return png.map(Self.imageWithinLimits) ?? false
    }
    static func imageWithinLimits(_ data: Data) -> Bool {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else { return false }
        return width > 0 && height > 0 && width <= 8000 && height <= 8000 && width * height <= 16_000_000
    }
    static func canRecord(types: Set<String>) -> Bool {
        types.isDisjoint(with: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.apple.is-remote-clipboard"])
    }
}

@MainActor
protocol ClipboardAccess: AnyObject {
    var changeCount: Int { get }
    func read() -> ClipboardEntry?
    func write(_ entry: ClipboardEntry)
}

@MainActor
final class SystemClipboardAccess: ClipboardAccess {
    var changeCount: Int { NSPasteboard.general.changeCount }
    func read() -> ClipboardEntry? {
        let board = NSPasteboard.general
        let types = Set((board.types ?? []).map(\.rawValue))
        guard ClipboardEntry.canRecord(types: types) else { return nil }
        if let text = board.string(forType: .string), !text.isEmpty, text.utf8.count <= 200_000 { return ClipboardEntry(text: text) }
        if let data = board.data(forType: .png), data.count <= 4_000_000, ClipboardEntry.imageWithinLimits(data) { return ClipboardEntry(png: data) }
        if let data = board.data(forType: .tiff), data.count <= 4_000_000, ClipboardEntry.imageWithinLimits(data),
           let image = NSBitmapImageRep(data: data), image.pixelsWide <= 8000, image.pixelsHigh <= 8000,
           let png = image.representation(using: .png, properties: [:]), png.count <= 4_000_000 { return ClipboardEntry(png: png) }
        return nil
    }
    func write(_ entry: ClipboardEntry) {
        let board = NSPasteboard.general; board.clearContents()
        if let text = entry.text { board.setString(text, forType: .string) }
        if let png = entry.png { board.setData(png, forType: .png) }
    }
}

@MainActor
final class PreviewClipboardAccess: ClipboardAccess {
    var changeCount = 0
    var value: ClipboardEntry?
    func read() -> ClipboardEntry? { value }
    func write(_ entry: ClipboardEntry) { value = entry; changeCount += 1 }
}

@MainActor
final class ClipboardToolsModel: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var enabled = false
    @Published private(set) var error: String?
    @Published var query = ""
    private let storage: ToolStorage<[ClipboardEntry]>
    private let access: any ClipboardAccess
    private let defaults: UserDefaults?
    private let enableTicker: Bool
    private var ticker: Timer?
    private var suspended = false
    private var lastChange: Int
    var needsRecovery: Bool { storage.damaged }
    var filtered: [ClipboardEntry] {
        entries.filter { query.isEmpty || ($0.text ?? "Image 圖片").localizedCaseInsensitiveContains(query) }
            .sorted { $0.pinned != $1.pinned ? $0.pinned : $0.date > $1.date }
    }
    init(defaults: UserDefaults?, access: any ClipboardAccess, enableTicker: Bool = true, root: URL? = nil) {
        self.defaults = defaults; self.access = access; self.enableTicker = enableTicker
        storage = ToolStorage(defaults, "tools.clipboard.v1", fileURL: root?.appendingPathComponent("history.json"))
        lastChange = access.changeCount
        entries = storage.load(fallback: [], validate: { items in
            items.count <= 50 && Set(items.map(\.id)).count == items.count && items.allSatisfy(\.valid) && items.reduce(0) { $0 + $1.byteCount } <= 16_000_000
        })
        if defaults?.bool(forKey: "tools.clipboard.enabled") == true, !needsRecovery { setEnabled(true) }
    }
    func setEnabled(_ value: Bool) {
        enabled = value && !needsRecovery; defaults?.set(enabled, forKey: "tools.clipboard.enabled")
        ticker?.invalidate(); ticker = nil; lastChange = access.changeCount
        if enabled, enableTicker {
            ticker = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in Task { @MainActor in self?.poll() } }
            ticker?.tolerance = 0.3
        }
    }
    func poll() {
        guard enabled, !suspended, access.changeCount != lastChange else { return }
        let version = access.changeCount; lastChange = version
        guard let entry = access.read(), entry.valid, access.changeCount == version else { return }
        admit(entry)
    }
    func admit(_ entry: ClipboardEntry) {
        guard entry.valid else { return }
        var values = entries
        if let index = values.firstIndex(where: { $0.text == entry.text && $0.png == entry.png }) {
            values[index].date = entry.date
        } else { values.insert(entry, at: 0) }
        while values.count > 50 || values.reduce(0, { $0 + $1.byteCount }) > 16_000_000 {
            guard let index = values.indices.filter({ !values[$0].pinned }).min(by: { values[$0].date < values[$1].date }) else {
                error = "Pinned items fill the drawer / 置頂項目已滿，請先移除部分項目"; return
            }
            values.remove(at: index)
        }
        persist(values)
    }
    func copy(_ entry: ClipboardEntry) { access.write(entry); lastChange = access.changeCount }
    func togglePin(_ entry: ClipboardEntry) {
        var values = entries; guard let index = values.firstIndex(where: { $0.id == entry.id }) else { return }
        values[index].pinned.toggle(); persist(values)
    }
    func remove(_ entry: ClipboardEntry) { persist(entries.filter { $0.id != entry.id }) }
    func clear() { persist([]) }
    func recover() {
        do { try storage.backupAndReset([]); entries = []; error = nil } catch { self.error = error.localizedDescription }
    }
    func stop() { ticker?.invalidate(); ticker = nil }
    func setSuspended(_ value: Bool) { suspended = value; lastChange = access.changeCount }
    private func persist(_ values: [ClipboardEntry]) {
        do { try storage.save(values); entries = values; error = nil } catch { self.error = error.localizedDescription }
    }
}
