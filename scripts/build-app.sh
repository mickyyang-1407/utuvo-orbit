#!/bin/bash
# Build UTUVO Orbit and bundle a runnable .app for local testing.
# ad-hoc signed, no Gatekeeper modifications, no remote upload.

set -euo pipefail
cd "$(dirname "$0")/.."

CONFIG="${CONFIG:-release}"
APP_NAME="UTUVO Orbit"
BUNDLE_ID="com.utuvo.orbit"
EXECUTABLE="UtuvoOrbit"
APP="${APP_OUTPUT_PATH:-$PWD/dist/$APP_NAME.app}"
VERSION="${VERSION:-0.11.0}"
BUILD_NUMBER="${BUILD_NUMBER:-16}"

echo "==> Building $EXECUTABLE ($CONFIG)…"
swift build -c "$CONFIG"

echo "==> Assembling $APP_NAME.app…"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
mkdir -p "$APP/Contents/Frameworks"
SPARKLE_FRAMEWORK="$PWD/.build/artifacts/sparkle/Sparkle/Sparkle.xcframework/macos-arm64_x86_64/Sparkle.framework"
ditto "$SPARKLE_FRAMEWORK" "$APP/Contents/Frameworks/Sparkle.framework"

cp ".build/$CONFIG/$EXECUTABLE" "$APP/Contents/MacOS/$EXECUTABLE"
chmod +x "$APP/Contents/MacOS/$EXECUTABLE"
cp "Resources/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
cp "Resources/Sparkle-LICENSE" "$APP/Contents/Resources/Sparkle-LICENSE"
# SwiftPM localized resources are needed by both the CLI and the packaged app.
cp -R ".build/$CONFIG/UtuvoOrbit_OrbitCore.bundle" "$APP/Contents/Resources/"
# File shelf module artwork (cat + tail).
cp -R ".build/$CONFIG/UtuvoOrbit_ShelfKit.bundle" "$APP/Contents/Resources/"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleExecutable</key><string>$EXECUTABLE</string>
<key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
<key>CFBundleName</key><string>$APP_NAME</string>
<key>CFBundleDisplayName</key><string>$APP_NAME</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleIconFile</key><string>AppIcon</string>
<key>CFBundleShortVersionString</key><string>$VERSION</string>
<key>CFBundleVersion</key><string>$BUILD_NUMBER</string>
<key>CFBundleDevelopmentRegion</key><string>en</string>
<key>CFBundleLocalizations</key><array><string>en</string><string>zh-Hant</string></array>
<key>LSMinimumSystemVersion</key><string>14.0</string>
<key>LSUIElement</key><true/>
<key>NSHighResolutionCapable</key><true/>
<key>NSScreenCaptureUsageDescription</key><string>Orbit captures the window or display you choose once, for local editing and export.</string>
<key>NSHumanReadableCopyright</key><string>© 2026 UTUVO</string>
<key>NSSupportsAutomaticTermination</key><true/>
<key>NSSupportsSuddenTermination</key><false/>
</dict></plist>
PLIST

# Public configuration only. Private signing material stays in Keychain.
# Ad-hoc previews can be unconfigured; release packaging must fail closed.
export ORBIT_BUILD_APP="$APP"
python3 - <<'PY'
import base64, os, plistlib
from pathlib import Path
from urllib.parse import urlparse
config = Path(os.environ.get('UPDATE_CONFIG', 'Resources/UpdateConfiguration.plist'))
settings = plistlib.loads(config.read_bytes()) if config.exists() else {}
feed = os.environ.get('SPARKLE_FEED_URL', settings.get('FeedURL', ''))
key = os.environ.get('SPARKLE_PUBLIC_KEY', settings.get('PublicEDKey', ''))
if key:
    url = urlparse(feed)
    if url.scheme != 'https' or not url.hostname or url.username or url.password:
        raise SystemExit('Update feed must use HTTPS without embedded credentials.')
    if len(base64.b64decode(key, validate=True)) != 32:
        raise SystemExit('Sparkle public key must decode to 32 bytes.')
    path = Path(os.environ['ORBIT_BUILD_APP']) / 'Contents/Info.plist'
    info = plistlib.loads(path.read_bytes())
    info.update(SUFeedURL=feed, SUPublicEDKey=key, SUEnableAutomaticChecks=True,
                SUAutomaticallyUpdate=False, SUEnableSystemProfiling=False,
                SUScheduledCheckInterval=86400, SUVerifyUpdateBeforeExtraction=True,
                SURequireSignedFeed=True)
    path.write_bytes(plistlib.dumps(info))
elif os.environ.get('REQUIRE_UPDATER') == '1':
    raise SystemExit('Release blocked: configure the production Sparkle public key first.')
else:
    print('Local preview: production updater is not configured.')
PY

# App icon is original vector artwork, generated by scripts/render-brand.swift.

echo "==> Ad-hoc signing…"
FRAMEWORK="$APP/Contents/Frameworks/Sparkle.framework/Versions/B"
codesign --force --sign - "$FRAMEWORK/XPCServices/Downloader.xpc"
codesign --force --sign - "$FRAMEWORK/XPCServices/Installer.xpc"
codesign --force --sign - "$FRAMEWORK/Updater.app"
codesign --force --sign - "$FRAMEWORK/Autoupdate"
codesign --force --sign - "$APP/Contents/Frameworks/Sparkle.framework"
codesign --force --sign - "$APP"
codesign --verify --deep --strict --verbose=2 "$APP"
plutil -lint "$APP/Contents/Info.plist"

printf '\nBuild complete: %s\n' "$APP"
printf '\nTry:\n  open "%s"\n  .build/%s/%s --diagnose\n  .build/%s/%s --gallery\n  .build/%s/%s --fixture laptop\n' \
  "$APP" "$CONFIG" "$EXECUTABLE" "$CONFIG" "$EXECUTABLE" "$CONFIG" "$EXECUTABLE"
